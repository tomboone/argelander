"""The schema, its migration, and both session factories, against a real Postgres.

The tests migrate a throwaway database beside the configured one (`<name>_test`), so the
dev database is never touched. They need DATABASE_URL: the dev stack's app container has
it, and CI runs a Postgres service for them. Outside CI they skip without it.
"""

import asyncio
import os
from collections.abc import Iterator

import pytest
from alembic import command
from sqlalchemy import Engine, create_engine, inspect, make_url, select, text
from sqlalchemy.exc import IntegrityError

from argelander.db.migrations import alembic_config, upgrade
from argelander.db.models import Base, Slice
from argelander.db.session import (
    async_session_factory,
    create_async_engine,
    create_sync_engine,
    sync_session_factory,
)

TABLES = {
    "slices",
    "targets",
    "light_curve_files",
    "jobs",
    "analyses",
    "proposals",
    "reviews",
    "submissions",
}


def _configured_url() -> str:
    try:
        return os.environ["DATABASE_URL"]
    except KeyError:
        if os.environ.get("CI") == "true":
            pytest.fail("DATABASE_URL is unset in CI; the job's Postgres service sets it")
        pytest.skip("needs DATABASE_URL (run inside the dev stack)")


@pytest.fixture(scope="module")
def database_url() -> Iterator[str]:
    """A freshly created, empty database on the configured server; dropped afterwards."""
    configured = make_url(_configured_url())
    name = f"{configured.database}_test"
    admin = create_engine(configured, isolation_level="AUTOCOMMIT")
    with admin.connect() as connection:
        connection.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        connection.execute(text(f'CREATE DATABASE "{name}"'))
    try:
        yield configured.set(database=name).render_as_string(hide_password=False)
    finally:
        with admin.connect() as connection:
            connection.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
        admin.dispose()


@pytest.fixture(scope="module")
def engine(database_url: str) -> Iterator[Engine]:
    upgrade("head", database_url)
    engine = create_sync_engine(database_url)
    yield engine
    engine.dispose()


def test_upgrade_creates_every_table_and_constraint(engine: Engine) -> None:
    schema = inspect(engine)

    assert set(schema.get_table_names()) - {"alembic_version"} == TABLES
    assert set(Base.metadata.tables) == TABLES

    for name, table in Base.metadata.tables.items():
        checks = {c["name"] for c in schema.get_check_constraints(name)}
        uniques = {c["name"] for c in schema.get_unique_constraints(name)}
        indexes = {i["name"] for i in schema.get_indexes(name)}
        foreign_keys = {f["name"] for f in schema.get_foreign_keys(name)}
        for constraint in table.constraints | table.indexes:
            if constraint.name is None or constraint.name.startswith("pk_"):
                continue
            assert constraint.name in checks | uniques | indexes | foreign_keys, (
                f"{name}: {constraint.name} is in the models but not the database"
            )

    jobs_index = {i["name"]: i["column_names"] for i in schema.get_indexes("jobs")}
    assert jobs_index["ix_jobs_kind_status_created_at"] == ["kind", "status", "created_at"]
    analyses_unique = schema.get_unique_constraints("analyses")
    assert [c["column_names"] for c in analyses_unique] == [["target_id", "pipeline_version"]]


def test_models_match_the_migration(engine: Engine, database_url: str) -> None:
    # Raises AutogenerateDiffsDetected if the models have drifted from the migrations.
    command.check(alembic_config(database_url))


def test_vocabulary_is_enforced_by_the_database(engine: Engine) -> None:
    with engine.connect() as connection, pytest.raises(IntegrityError, match="ck_jobs_kind"):
        connection.execute(text("INSERT INTO jobs (kind, target_id) VALUES ('reduce', 1)"))


def test_sync_and_async_sessions(engine: Engine, database_url: str) -> None:
    sessions = sync_session_factory(engine)
    with sessions.begin() as session:
        session.add(
            Slice(
                name="Dra-13-16",
                constellation="Dra",
                mag_min=13.0,
                mag_max=16.0,
                pipeline_version="0.1.0",
            )
        )

    async def read_back() -> list[str]:
        async_engine = create_async_engine(database_url)
        try:
            async with async_session_factory(async_engine)() as session:
                return list((await session.scalars(select(Slice.name))).all())
        finally:
            await async_engine.dispose()

    assert asyncio.run(read_back()) == ["Dra-13-16"]


def test_downgrade_removes_every_table(database_url: str, engine: Engine) -> None:
    config = alembic_config(database_url)
    command.downgrade(config, "base")
    try:
        assert set(inspect(engine).get_table_names()) == {"alembic_version"}
    finally:
        command.upgrade(config, "head")
